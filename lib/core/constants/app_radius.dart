/// Definisi border radius aplikasi PetCare sesuai dengan Design System.
class AppRadius {
  // Private constructor agar class ini tidak dapat diinstansiasi
  AppRadius._();

  /// Border radius untuk chip, badge, tag (8.0)
  static const double sm = 8.0;
  static const double chip = 8.0;

  /// Border radius untuk tombol, input field, icon container (12.0)
  static const double md = 12.0;
  static const double btn = 12.0;

  /// Border radius untuk card, container (16.0)
  static const double lg = 16.0;
  static const double card = 16.0;

  /// Border radius untuk bottom sheet (top only), modal (24.0)
  static const double xl = 24.0;

  /// Border radius untuk avatar, tombol bulat, pill (999.0)
  static const double full = 999.0;
}
